#!/usr/bin/env python3
"""Emit absolute linker pins only for symbols that remain genuinely unresolved.

Splat's auto undefined scripts are retained as an address/name catalogue, but
must not be linked wholesale: an assignment in a linker script overrides a
real object definition and can hide successful decompilation work.
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path


ASSIGN_RE = re.compile(r"^([\w.]+)\s*=")
ABS_ASSIGN_RE = re.compile(r"^([\w.]+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*;")
ADDRESS_NAME_RE = re.compile(
    r"^(?:D_|func_|jlabel_|jtbl_|jpt_|\.L)[0-9A-Fa-f]{8}$"
)


def parse_symbol_table(text: str) -> tuple[set[str], set[str]]:
    undefined: set[str] = set()
    defined: set[str] = set()
    for line in text.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] == "U":
            undefined.add(parts[1])
        elif len(parts) == 3 and parts[1] in ("C", "c"):
            # Tentative COMMON symbols have no accepted BSS placement yet.
            # Treat them as unresolved even if no other object has a U record:
            # the defining object's relocations still require the absolute pin.
            undefined.add(parts[2])
        elif len(parts) == 3 and parts[1] != "U":
            defined.add(parts[2])
    return undefined, defined


def symbol_tables(nm: str, objects: list[Path]) -> tuple[set[str], set[str]]:
    result = subprocess.run(
        [nm, *(str(obj) for obj in objects)],
        check=True,
        stdout=subprocess.PIPE,
        text=True,
    )
    return parse_symbol_table(result.stdout)


def assigned_names(paths: list[Path]) -> set[str]:
    names = set()
    for path in paths:
        if path.exists():
            for line in path.read_text().splitlines():
                match = ASSIGN_RE.match(line)
                if match:
                    names.add(match.group(1))
    return names


def known_addresses(paths: list[Path]) -> dict[str, int]:
    known = {}
    for path in paths:
        if path.exists():
            for line in path.read_text().splitlines():
                match = ABS_ASSIGN_RE.match(line)
                if match:
                    known.setdefault(match.group(1), int(match.group(2), 0))
    return known


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("objects", nargs="+", type=Path)
    parser.add_argument("--nm", default="mipsel-none-elf-nm")
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--source", action="append", default=[], type=Path)
    parser.add_argument("--manual", action="append", default=[], type=Path)
    args = parser.parse_args()

    undefined, defined = symbol_tables(args.nm, args.objects)
    unresolved = undefined - defined - assigned_names(args.manual)
    known = known_addresses(args.source)
    pins = []
    missing = []
    for symbol in sorted(unresolved):
        if symbol in known:
            pins.append((known[symbol], symbol))
        else:
            missing.append(symbol)

    suspicious = [symbol for symbol in missing if ADDRESS_NAME_RE.match(symbol)]
    if suspicious:
        print("ERROR: unresolved address symbols have no known address:")
        for symbol in suspicious:
            print(f"  {symbol}")
        return 1

    lines = [
        "/* Absolute addresses still referenced but defined by no linked object. */",
        "/* Generated by tools/scripts/gen_undefined_addr_aliases.py. */",
    ]
    lines.extend(
        f"{symbol} = 0x{address:08X};"
        for address, symbol in sorted(pins)
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(lines) + "\n"
    if not args.output.exists() or args.output.read_text() != text:
        args.output.write_text(text, encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
